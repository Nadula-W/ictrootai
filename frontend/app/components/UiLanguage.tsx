export function translateUi(text: string, language: string = 'en', values?: Values): string {
  const translated = language === 'si' ? sinhala[text] ?? text : text;
  return values ? translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => values[key] === undefined ? placeholder : String(values[key])) : translated;
}

const UiContext = createContext<UiContextValue>({language:'en',t:(text,values)=>translateUi(text,'en',values)});

export function UiProvider({language, children}: {language: string; children: ReactNode}) {
  const normalized: UiLanguage = language === 'si' ? 'si' : 'en';
  const value = useMemo<UiContextValue>(() => ({language:normalized,t:(text,values)=>translateUi(text,normalized,values)}), [normalized]);
  return <UiContext.Provider value={value}>{children}</UiContext.Provider>;
}

export function useUi() {return useContext(UiContext);}
